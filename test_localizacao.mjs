import assert from 'node:assert/strict';
import {distanceMeters,bearingDegrees,accuracyGeometry,DEMO_ROUTE,sampleRoute,cardinal,validCoords,geolocationMessage} from './localizacao.js';
assert.ok(distanceMeters([-46.6333,-23.5505],[-46.6333,-23.5505])<0.001);
assert.ok(distanceMeters([-46.6333,-23.5505],[-46.6333,-23.5515])>100);
assert.ok(Math.abs(bearingDegrees([0,0],[1,0])-90)<0.001);
assert.equal(cardinal(270),'O');
assert.equal(cardinal(44),'NE');
assert.equal(validCoords([0,0]),true);
assert.equal(validCoords([-200,0]),false);
assert.equal(geolocationMessage({code:1}).includes('negada'),true);
const area=accuracyGeometry([-46.65,-23.56],20);
assert.equal(area.features[0].geometry.coordinates[0].length,49);
assert.ok(distanceMeters(area.features[0].geometry.coordinates[0][0],[-46.65,-23.56])>19);
assert.ok(distanceMeters(area.features[0].geometry.coordinates[0][0],[-46.65,-23.56])<21);
assert.deepEqual(sampleRoute(DEMO_ROUTE,0).coords,DEMO_ROUTE[0]);
assert.deepEqual(sampleRoute(DEMO_ROUTE,1).coords,DEMO_ROUTE.at(-1));
const mid=sampleRoute(DEMO_ROUTE,0.5);
assert.ok(mid.coords[0]>DEMO_ROUTE[0][0]&&mid.coords[0]<DEMO_ROUTE.at(-1)[0]);
console.log('RadarSP v0.3: 12 verificações da lógica de localização aprovadas.');
